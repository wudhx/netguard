"""Agent 层：模型驱动的缺陷假设提出。

## 这一层存在的唯一理由

确定性代码能回答「这条规则报不报」，不能回答「这里看起来有没有问题」。
后者需要「觉得」——一种基于运维语义而非既定判据的判断力。

本项目里，这个能力只在一处产生不可替代的价值：**对抗式缺陷发现**。

规则由人写，测试语料由人写，于是「规则抓到了我造的缺陷」证明不了什么——
人只能造出自己想到的缺陷，而想到的恰好已经是规则覆盖的那批。这是自我循环。

打破循环需要一方**不掌握规则知识**的独立观察者。它读配置，只按「这台设备
运维上说不说得通」提出假设；假设是否成立由代码裁决（`core/eval_inject.py`）。

## 三方分离（不可合并）

| 角色 | 谁 | 产出 | 判定权 |
|---|---|---|---|
| 提议 | 模型 | 缺陷假设（位置 / 类别 / 理由） | 无 |
| 裁决 | 代码 | 假设是否成立 | 有 |
| 判定 | 规则引擎 | 哪些缺陷被报出 | 有 |

模型对「哪里有缺陷」有提议权，没有裁定权。它提的假设可能不成立——
不成立的假设被 `lookup()` 驳掉，且**不计入规则召回率的分母**。
"""

